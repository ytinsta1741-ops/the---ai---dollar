class HealthHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        path = self.path

        if path == f"/{TIKTOK_VERIFICATION_FILE}":
            self.send_response(200)
            self.send_header("Content-Type", "text/plain")
            self.end_headers()
            self.wfile.write(TIKTOK_VERIFICATION_CONTENT)

        elif path.startswith("/tiktok-callback"):
            import urllib.parse as _up
            query = _up.urlparse(path).query
            params = _up.parse_qs(query)
            code = params.get("code", [""])[0]
            error = params.get("error", [""])[0]
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.end_headers()
            if code:
                body = (
                    f"<h1>Success</h1><p>Copy this code and paste it back into "
                    f"get_tiktok_token.py:</p><pre style='font-size:18px;background:#eee;"
                    f"padding:12px'>{code}</pre>"
                ).encode()
            else:
                body = f"<h1>Error</h1><p>{error or 'No code received'}</p>".encode()
            self.wfile.write(body)

        elif path == "/privacy":
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.end_headers()
            self.wfile.write(PRIVACY_POLICY_HTML)

        elif path == "/terms":
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.end_headers()
            self.wfile.write(TERMS_OF_SERVICE_HTML)

        elif path == "/test-tiktok":
            print("\n[TEST] Manual TikTok test triggered!")
            try:
                import glob
                videos = sorted(glob.glob("./videos/*.mp4"), key=os.path.getmtime, reverse=True)
                if not videos:
                    msg = b"[ERR] No video files found in ./videos yet"
                else:
                    video_path = videos[0]
                    print(f"[TEST] Using existing video: {video_path}")
                    success = upload_to_tiktok(video_path, "The AI Dollar — Personal Finance Made Simple")
                    msg = b"[OK] TikTok test posted!" if success else b"[ERR] TikTok test failed"
            except Exception as e:
                msg = f"[ERR] {str(e)}".encode()
            self.send_response(200)
            self.end_headers()
            self.wfile.write(msg)

        elif path.startswith("/media/"):
            filename = os.path.basename(path[len("/media/"):])
            filepath = os.path.join("./videos", filename)
            if filename.endswith(".mp4") and os.path.exists(filepath):
                self.send_response(200)
                self.send_header("Content-Type", "video/mp4")
                self.send_header("Content-Length", str(os.path.getsize(filepath)))
                self.end_headers()
                with open(filepath, 'rb') as f:
                    self.wfile.write(f.read())
            else:
                self.send_response(404)
                self.end_headers()
                self.wfile.write(b"Not found")

        else:
            self.send_response(200)
            self.end_headers()
            self.wfile.write(b"The AI Dollar is running!")

    def log_message(self, format, *args):
        pass


