def upload_to_tiktok(video_path, title, keywords=None):
    """Upload video to TikTok using the official Content Posting API."""
    client_key = os.getenv("TIKTOK_CLIENT_KEY", "").strip()
    client_secret = os.getenv("TIKTOK_CLIENT_SECRET", "").strip()
    refresh_token = os.getenv("TIKTOK_REFRESH_TOKEN", "").strip()

    if not client_key or not client_secret or not refresh_token:
        print("[SKIP] TikTok: TIKTOK_CLIENT_KEY/CLIENT_SECRET/REFRESH_TOKEN not fully set")
        return False

    print(f"[TikTok] client_key len={len(client_key)} repr={client_key[:4]!r}...{client_key[-4:]!r}")
    print(f"[TikTok] client_secret len={len(client_secret)}")
    print(f"[TikTok] refresh_token len={len(refresh_token)} repr={refresh_token[:8]!r}...{refresh_token[-8:]!r}")

    try:
        import requests as req

        kw_tags = " ".join(f"#{k.replace(' ', '')}" for k in (keywords or [])[:3])
        caption = (
            f"{title[:60]} "
            f"#moneytok #fintok #investing #finance #personalfinance "
            f"#moneytips #financialfreedom #wealthbuilding "
            f"#learnontiktok #fyp #viral {kw_tags}"
        )[:150]

        print("[TikTok] Refreshing access token...")
        token_resp = req.post(
            "https://open.tiktokapis.com/v2/oauth/token/",
            headers={"Content-Type": "application/x-www-form-urlencoded"},
            data={
                "client_key": client_key,
                "client_secret": client_secret,
                "grant_type": "refresh_token",
                "refresh_token": refresh_token,
            },
            timeout=20,
        )
        token_data = token_resp.json()
        access_token = token_data.get("access_token")
        if not access_token:
            print(f"[ERR] TikTok token refresh failed: {token_data}")
            return False

        auth_headers = {
            "Authorization": f"Bearer {access_token}",
            "Content-Type": "application/json; charset=UTF-8",
        }

        print("[TikTok] Querying creator info...")
        creator_resp = req.post(
            "https://open.tiktokapis.com/v2/post/publish/creator_info/query/",
            headers=auth_headers,
            timeout=20,
        )
        creator_data = creator_resp.json().get("data", {})
        privacy_options = creator_data.get("privacy_level_options", ["SELF_ONLY"])

        # Unaudited apps can ONLY post as SELF_ONLY, even if PUBLIC_TO_EVERYONE
        # is listed as an option — TikTok's posting endpoint enforces this
        # separately from what creator_info reports. Flip TIKTOK_AUDITED=true
        # on Render once the app passes review to allow public posting.
        if os.getenv("TIKTOK_AUDITED", "false").lower() == "true" and "PUBLIC_TO_EVERYONE" in privacy_options:
            privacy_level = "PUBLIC_TO_EVERYONE"
        else:
            privacy_level = "SELF_ONLY"
        print(f"[TikTok] Privacy level: {privacy_level}")

        file_size = os.path.getsize(video_path)
        print(f"[TikTok] Video size: {file_size / 1024 / 1024:.1f}MB")

        print("[TikTok] Initializing post...")
        init_resp = req.post(
            "https://open.tiktokapis.com/v2/post/publish/video/init/",
            headers=auth_headers,
            json={
                "post_info": {
                    "title": caption,
                    "privacy_level": privacy_level,
                    "disable_duet": False,
                    "disable_comment": False,
                    "disable_stitch": False,
                    "video_cover_timestamp_ms": 1000,
                },
                "source_info": {
                    "source": "FILE_UPLOAD",
                    "video_size": file_size,
                    "chunk_size": file_size,
                    "total_chunk_count": 1,
                },
            },
            timeout=20,
        )
        init_data = init_resp.json()
        if "data" not in init_data or "publish_id" not in init_data["data"]:
            print(f"[ERR] TikTok init failed: {init_data}")
            return False

        publish_id = init_data["data"]["publish_id"]
        upload_url = init_data["data"]["upload_url"]

        print("[TikTok] Uploading video...")
        with open(video_path, 'rb') as f:
            video_data = f.read()

        upload_resp = req.put(
            upload_url,
            headers={
                "Content-Type": "video/mp4",
                "Content-Range": f"bytes 0-{file_size - 1}/{file_size}",
            },
            data=video_data,
            timeout=120,
        )
        print(f"[TikTok] Upload response: {upload_resp.status_code}")
        if upload_resp.status_code not in (200, 201):
            print(f"[ERR] TikTok upload failed: {upload_resp.status_code} - {upload_resp.text[:200]}")
            return False

        print("[TikTok] Checking publish status...")
        for _ in range(6):
            time.sleep(5)
            status_resp = req.post(
                "https://open.tiktokapis.com/v2/post/publish/status/fetch/",
                headers=auth_headers,
                json={"publish_id": publish_id},
                timeout=20,
            )
            status_data = status_resp.json().get("data", {})
            status = status_data.get("status")
            print(f"[TikTok] Status: {status}")
            if status == "PUBLISH_COMPLETE":
                print(f"[OK] TikTok posted! Title: {title[:50]}")
                return True
            if status == "FAILED":
                print(f"[ERR] TikTok publish failed: {status_data}")
                return False

        print("[WARN] TikTok publish status unknown after polling, treating as posted")
        return True

    except Exception as e:
        print(f"[ERR] TikTok error: {e}")
        return False


def schedule_jobs():
    # SHORTS ONLY — discovery engine for small channels
    # Shorts get shown on the Shorts shelf to non-subscribers
    # 6 per day, spaced across US peak SCROLLING windows (times in UTC, EDT = UTC-4)
    # Replaced the old 2am EDT slot (dead time) with a second prime-time slot.
    # Instagram Reels reach drops off with over-posting (Meta's own creator
    # guidance points to ~1-2/day), unlike YouTube Shorts/TikTok which
    # reward volume — so only the two strongest windows (lunch + prime
    # time) also go to Instagram; the rest post YouTube + TikTok only.
    schedule.every().day.at("11:00").do(post_video, post_instagram=False)  # US East 7am — wake up / commute scroll
    schedule.every().day.at("15:30").do(post_video, post_instagram=True)   # US East 11:30am — lunch break
    schedule.every().day.at("18:00").do(post_video, post_instagram=False)  # US East 2pm — afternoon slump scroll
    schedule.every().day.at("21:00").do(post_video, post_instagram=False)  # US East 5pm — evening commute
    schedule.every().day.at("23:30").do(post_video, post_instagram=True)   # US East 7:30pm — prime time
    schedule.every().day.at("01:30").do(post_video, post_instagram=False)  # US East 9:30pm — late-night scroll (peak Shorts engagement)

    schedule.every(10).minutes.do(keep_alive)
    print("[OK] Schedule: 6 Shorts/day on YouTube+TikTok, 2/day on Instagram (growth mode)")
    print("[OK] Shorts = discovery engine for non-subscribers")
    print("[OK] Self-ping every 10 min to prevent Render spin-down")


